  const getStoredLanguage = () => {
    try {
      const stored = localStorage.getItem(storageKey);
      return stored === 'ar' || stored === 'en' ? stored : null;
    } catch (error) {
      return null;
    }
  };

  const applyLanguage = language => {
    const nextLanguage = language === 'ar' ? 'ar' : 'en';
    root.lang = nextLanguage;
    root.dir = nextLanguage === 'ar' ? 'rtl' : 'ltr';
    root.dataset.siteLang = nextLanguage;
    root.classList.toggle('site-lang-ar', nextLanguage === 'ar');
    root.classList.toggle('site-lang-en', nextLanguage === 'en');
    if (toggleLabel) {
      toggleLabel.textContent = nextLanguage === 'ar' ? 'AR' : 'EN';
    }
    if (toggleTrigger) {
      toggleTrigger.setAttribute(
        'aria-label',
        nextLanguage === 'ar' ? 'Language switch, current language Arabic' : 'Language switch, current language English'
      );
    }

    translatedNodes.forEach(node => {
      const key = node.dataset.i18nKey;
      const translation = translations[nextLanguage][key];
      if (translation) {
        node.textContent = translation;
      }
    });

    translatedPlaceholders.forEach(node => {
      const key = node.dataset.i18nPlaceholderKey;
      const translation = translations[nextLanguage][key];
      if (translation) {
        node.setAttribute('placeholder', translation);
      }
    });

    toggleButtons.forEach(button => {
      const isActive = button.dataset.siteLanguage === nextLanguage;
      button.classList.toggle('active', isActive);
      button.setAttribute('aria-pressed', String(isActive));
    });

    try {
      localStorage.setItem(storageKey, nextLanguage);
    } catch (error) {
      // Ignore storage failures in private or restricted modes.
    }

    window.dispatchEvent(
      new CustomEvent('gocloud:language-change', {
        detail: { language: nextLanguage }
      })
    );
  };

  const initialLanguage = getStoredLanguage() || 'en';
  applyLanguage(initialLanguage);

  toggleButtons.forEach(button => {
    button.addEventListener('click', () => {
      applyLanguage(button.dataset.siteLanguage || 'en');
    });
  });

  if (toggleTrigger) {
    toggleTrigger.addEventListener('keydown', event => {
      if (event.key === 'ArrowDown' || event.key === 'Enter' || event.key === ' ') {
        const firstItem = document.querySelector('[data-site-language="ar"]');
        if (firstItem) {
          event.preventDefault();
        }
      }
    });
  }
